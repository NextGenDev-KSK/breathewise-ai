"use client";

import { useEffect, useId, useRef, useState } from "react";
import Link from "next/link";
import { LoaderCircle, Send, Sparkles, Trash2, User } from "lucide-react";
import { useApp } from "@/components/app/AppProvider";
import { Card } from "@/components/ui/Card";
import { Badge } from "@/components/ui/Badge";
import { Button } from "@/components/ui/Button";
import { AssistantAnswer } from "@/components/assistant/AssistantAnswer";
import { MAX_HISTORY, MAX_MESSAGE_LENGTH, type AssistantResponse } from "@/lib/ai/schema";
import { buildAssistantContext } from "@/lib/ai/context";
import { buildRuleBasedAnswer } from "@/lib/ai/fallback";
import { askGemini, fetchAssistantStatus } from "@/lib/ai/client";

interface Turn {
  id: number;
  question: string;
  answer: AssistantResponse | null;
  source: { kind: "gemini"; model: string } | { kind: "rules" };
  notice?: string;
}

const SUGGESTIONS = [
  "Is it a good time to go walking?",
  "How can I improve air quality in my bedroom?",
  "My child has school tomorrow. What precautions should I consider?",
  "Suggest a low-emission commute.",
  "Create a daily routine for my family.",
  "Why is PM2.5 particularly concerning?",
  "What should I change based on today's pollution levels?",
];

const FALLBACK_NOTICES: Record<string, string> = {
  ai_not_configured: "Gemini is not configured on this server, so this answer was generated by BreatheWise's rule engine.",
  ai_timeout: "Gemini took too long to respond, so this answer comes from the rule engine.",
  ai_unavailable: "Gemini is temporarily unavailable, so this answer comes from the rule engine.",
  ai_invalid_output: "Gemini's response failed BreatheWise's safety and accuracy checks and was discarded. This answer comes from the rule engine.",
  rate_limited: "Too many questions in a short time. This answer comes from the rule engine.",
  network: "The assistant service could not be reached. This answer comes from the rule engine.",
};

export function AssistantChat() {
  const { air, preferences, nowMs, formatTime, settings } = useApp();
  const [turns, setTurns] = useState<Turn[]>([]);
  const [input, setInput] = useState("");
  const [pending, setPending] = useState(false);
  const [configured, setConfigured] = useState<boolean | null>(null);
  const [error, setError] = useState<string | null>(null);
  const controllerRef = useRef<AbortController | null>(null);
  const nextId = useRef(1);
  const inputId = useId();
  const countId = useId();
  const errorId = useId();
  const listRef = useRef<HTMLOListElement>(null);

  useEffect(() => {
    const c = new AbortController();
    fetchAssistantStatus(c.signal).then(setConfigured);
    return () => {
      c.abort();
      controllerRef.current?.abort();
    };
  }, []);

  const snapshot = air.snapshot;
  const aiActive = settings.aiEnabled && configured === true && snapshot !== null;
  const modeLabel = !settings.aiEnabled
    ? "Rule-based mode: AI is turned off in Settings"
    : configured === null
      ? "Checking AI availability…"
      : configured
        ? snapshot
          ? "Gemini AI, grounded in your local data"
          : "Rule-based mode until a location is selected"
        : "Rule-based mode: Gemini is not configured";

  async function ask(question: string) {
    const q = question.trim();
    if (!q) {
      setError("Please enter a question.");
      return;
    }
    if (q.length > MAX_MESSAGE_LENGTH) {
      setError(`Questions are limited to ${MAX_MESSAGE_LENGTH} characters.`);
      return;
    }
    setError(null);
    setInput("");
    controllerRef.current?.abort();
    const controller = new AbortController();
    controllerRef.current = controller;
    const id = nextId.current++;
    const fallback = () => buildRuleBasedAnswer({ message: q, snapshot, preferences, nowMs, formatTime });

    if (!aiActive || !snapshot) {
      setTurns((t) => [...t, { id, question: q, answer: fallback(), source: { kind: "rules" }, notice: !settings.aiEnabled ? "AI is turned off in Settings. This answer comes from the rule engine." : configured === false ? FALLBACK_NOTICES.ai_not_configured : undefined }]);
      return;
    }

    setPending(true);
    setTurns((t) => [...t, { id, question: q, answer: null, source: { kind: "rules" } }]);
    const history = turns.slice(-MAX_HISTORY / 2).flatMap((t) => [
      { role: "user" as const, text: t.question.slice(0, 1200) },
      { role: "assistant" as const, text: (t.answer?.summary ?? "").slice(0, 1200) },
    ]);
    try {
      const result = await askGemini(q, history, buildAssistantContext(snapshot, preferences, nowMs), controller.signal);
      setTurns((all) =>
        all.map((t) =>
          t.id !== id
            ? t
            : result.ok
              ? { ...t, answer: result.response, source: { kind: "gemini", model: result.model } }
              : { ...t, answer: fallback(), source: { kind: "rules" }, notice: FALLBACK_NOTICES[result.code] ?? "The AI response was unavailable, so this answer comes from the rule engine." },
        ),
      );
    } catch {
      setTurns((all) => all.filter((t) => t.id !== id)); // aborted
    } finally {
      if (controllerRef.current === controller) setPending(false);
    }
  }

  useEffect(() => {
    const reduce = window.matchMedia?.("(prefers-reduced-motion: reduce)").matches;
    listRef.current?.lastElementChild?.scrollIntoView?.({ block: "nearest", behavior: reduce ? "auto" : "smooth" });
  }, [turns]);

  return (
    <div className="grid gap-6 lg:grid-cols-[1fr_18rem]">
      <Card className="flex min-h-[32rem] flex-col">
        <div className="flex flex-wrap items-center justify-between gap-2 border-b border-line px-5 py-3">
          <p className="flex items-center gap-2 text-sm font-medium text-ink-2" role="status">
            <Sparkles aria-hidden="true" className="size-4 text-brand-700" />
            {modeLabel}
          </p>
          {turns.length ? (
            <Button size="sm" variant="ghost" onClick={() => setTurns([])}>
              <Trash2 aria-hidden="true" className="size-4" /> Clear conversation
            </Button>
          ) : null}
        </div>

        <div className="flex-1 overflow-y-auto px-5 py-4">
          {turns.length === 0 ? (
            <div className="py-6 text-center">
              <p className="text-base font-semibold text-ink">Ask about your air, your home or your commute</p>
              <p className="mx-auto mt-1 max-w-md text-sm text-ink-3">
                Answers use the current data for {snapshot ? (snapshot.origin === "demo" ? "the sample location" : snapshot.place.name) : "your location once selected"}. Conversations are not saved.
              </p>
              {!snapshot ? (
                <p className="mt-3 text-sm">
                  <Link href="/" className="font-semibold text-brand-700 underline">Choose a location</Link> for answers based on local data.
                </p>
              ) : null}
            </div>
          ) : (
            <ol ref={listRef} aria-label="Conversation" className="space-y-6">
              {turns.map((t) => (
                <li key={t.id} className="space-y-3">
                  <div className="flex justify-end">
                    <p className="flex max-w-[85%] items-start gap-2 rounded-2xl rounded-br-sm bg-navy-900 px-4 py-2.5 text-sm text-white">
                      <User aria-hidden="true" className="mt-0.5 size-4 shrink-0 text-navy-300" />
                      <span>
                        <span className="sr-only">You asked: </span>
                        {t.question}
                      </span>
                    </p>
                  </div>
                  <div className="rounded-2xl rounded-bl-sm border border-line bg-canvas p-4" aria-live="polite" aria-busy={!t.answer}>
                    {t.answer ? (
                      <AssistantAnswer answer={t.answer} source={t.source} notice={t.notice} />
                    ) : (
                      <p className="flex items-center gap-2 text-sm text-ink-3">
                        <LoaderCircle aria-hidden="true" className="size-4 animate-spin" /> Thinking with your local data…
                      </p>
                    )}
                  </div>
                </li>
              ))}
            </ol>
          )}
        </div>

        <form
          onSubmit={(e) => {
            e.preventDefault();
            void ask(input);
          }}
          className="border-t border-line p-4"
        >
          <label htmlFor={inputId} className="text-sm font-semibold text-ink">
            Your question
          </label>
          <div className="mt-1.5 flex items-end gap-2">
            <textarea
              id={inputId}
              rows={2}
              value={input}
              maxLength={MAX_MESSAGE_LENGTH}
              onChange={(e) => setInput(e.target.value)}
              onKeyDown={(e) => {
                if (e.key === "Enter" && !e.shiftKey) {
                  e.preventDefault();
                  void ask(input);
                }
              }}
              aria-describedby={`${countId}${error ? ` ${errorId}` : ""}`}
              aria-invalid={error ? true : undefined}
              placeholder="e.g. Is this evening better for a jog?"
              className="min-h-11 flex-1 resize-y rounded-lg border border-line-strong px-3 py-2 text-sm"
            />
            <Button type="submit" disabled={pending}>
              {pending ? <LoaderCircle aria-hidden="true" className="size-4 animate-spin" /> : <Send aria-hidden="true" className="size-4" />}
              <span className="sr-only sm:not-sr-only">Ask</span>
            </Button>
          </div>
          <div className="mt-1 flex justify-between gap-2 text-xs">
            <p id={errorId} role="alert" className="font-semibold text-danger-700">
              {error}
            </p>
            <p id={countId} className="text-ink-3">
              {input.length}/{MAX_MESSAGE_LENGTH} characters. Enter to send, Shift+Enter for a new line.
            </p>
          </div>
        </form>
      </Card>

      <aside aria-labelledby="suggest-heading" className="space-y-4">
        <Card className="p-4">
          <h2 id="suggest-heading" className="text-sm font-semibold text-ink">
            Try asking
          </h2>
          <ul className="mt-3 space-y-2">
            {SUGGESTIONS.map((s) => (
              <li key={s}>
                <button type="button" onClick={() => void ask(s)} disabled={pending} className="min-h-11 w-full rounded-lg border border-line px-3 py-2 text-left text-sm text-ink-2 hover:border-brand-600 hover:bg-brand-50 disabled:opacity-60">
                  {s}
                </button>
              </li>
            ))}
          </ul>
        </Card>
        <Card className="space-y-2 p-4 text-xs text-ink-3">
          <p className="font-semibold text-ink-2">How answers are made</p>
          <p>Only your city name, the current air readings, the next 24 hours of forecast and your saved preferences are sent. Coordinates are never sent to the AI.</p>
          <p>Every AI answer is checked against a strict format and against the supplied numbers. If a check fails, the rule-based answer is shown instead.</p>
          <Badge tone="neutral">Not medical advice</Badge>
        </Card>
      </aside>
    </div>
  );
}
